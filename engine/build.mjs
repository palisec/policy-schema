#!/usr/bin/env node
/**
 * Builds the engine to WebAssembly and embeds it in packages/policy-engine/src/wasm.ts, with the
 * hash of the Rust sources it was built from. CI fails if the sources change without a rebuild.
 *
 *   node services/policy-engine/build.mjs           build and write wasm.ts
 *   node services/policy-engine/build.mjs --hash    print the current source hash only
 *
 * Needs cargo with the wasm32-unknown-unknown target. On Windows without the MSVC build tools,
 * use the GNU toolchain: RUSTUP_TOOLCHAIN=stable-x86_64-pc-windows-gnu.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { sourceHash } from "./source-hash.mjs";

const here = fileURLToPath(new URL(".", import.meta.url));
const hash = sourceHash(here);
if (process.argv.includes("--hash")) {
  console.log(hash);
  process.exit(0);
}

execFileSync("cargo", ["build", "--release", "--locked", "--target", "wasm32-unknown-unknown"], { cwd: here, stdio: "inherit" });
// CARGO_TARGET_DIR is honoured (a target path without spaces helps the Windows GNU linker).
const targetDir = process.env.CARGO_TARGET_DIR ?? join(here, "target");
const wasm = readFileSync(join(targetDir, "wasm32-unknown-unknown", "release", "palisec_policy_engine.wasm"));
const version = /^version = "([^"]+)"/m.exec(readFileSync(new URL("./Cargo.toml", import.meta.url), "utf8"))[1];
const out = new URL("../engine-wasm/src/wasm.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by services/policy-engine/build.mjs. Do not edit.\n` +
    `export const ENGINE_VERSION = ${JSON.stringify(version)};\n` +
    `/** SHA-256 of the Rust sources this module was built from. */\n` +
    `export const SOURCE_HASH = ${JSON.stringify(hash)};\n` +
    `export const WASM_BASE64 =\n  ${JSON.stringify(wasm.toString("base64"))};\n`,
);
console.log(`policy engine ${version}: ${wasm.length} bytes, source ${hash.slice(0, 12)}`);
